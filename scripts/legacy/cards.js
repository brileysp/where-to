/* ---------------------------------------------------------------------
   Where To? — Travel DNA experience card dataset
   -----------------------------------------------------------------
   Single structured data file for the Travel DNA Builder's swipe deck.

   Cards are deliberately specific, sensory moments — not generic
   activities and NOT tied to any named destination. ("A muddy 3-hour
   hike to a 20-meter waterfall with nobody there," not "Go hiking" and
   not "Visit Bali.") Keeping place names out entirely is intentional:
   the card should be judged purely on whether the EXPERIENCE appeals,
   not on brand associations with a country or city.

   HOW TO ADD MORE CARDS LATER (scales to hundreds/thousands with zero
   app-logic changes):
     1. Append a new object to EXPERIENCE_CARDS below, following the
        same shape (id, title, description, category, tags,
        imagePrompt, preferenceSignals).
     2. Use a unique, descriptive snake_case id.
     3. category should ideally be one of CARD_CATEGORIES (adding a new
        category is fine — just add it to CARD_CATEGORIES too so it
        gets a visual style and participates in diversity/coverage logic).
     4. preferenceSignals keys must come from PREFERENCE_ATTRIBUTES in
        traveldna.js. Signals are small integers, typically -3..+3 —
        they're multipliers applied per swipe, not absolute scores.
     5. Write the title/description as a specific, concrete MOMENT with
        real quantities (time, distance, size, count) — not a category
        label. Never name a real country, city, region or landmark.
     6. No image files needed — imagePrompt is a short visual/mood
        description used to pick a placeholder gradient + render a
        caption; there is no external image API in this prototype.
   The card-selection, scoring, calibration and UI code never assumes a
   fixed card count or a fixed category list, so this file can grow
   arbitrarily large without touching traveldna.js, dna-ui.js or app.js.
--------------------------------------------------------------------- */

