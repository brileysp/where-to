// 21 Oct 2026: rebuilds src/lib/text/bird-names.ts, the list of bird names the species-case checker looks for, from the headline birds in the
// birding facts. Only entries that already look like a full bird name (one to four words, every word capitalized, hyphens allowed) are kept.
// Usage: PLACE_ROWS_SNAPSHOT=1 npx tsx scripts/build-bird-case-list.ts
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
for (const line of readFileSync(join(__dirname, '..', '.env.local'), 'utf8').split('\n')) { const t = line.trim(); if (!t || t.startsWith('#')) continue; const i = t.indexOf('='); if (i < 0) continue; let v = t.slice(i + 1).trim(); if (/^["'].*["']$/.test(v)) v = v.slice(1, -1); if (process.env[t.slice(0, i).trim()] === undefined) process.env[t.slice(0, i).trim()] = v; }
(async () => {
  const { db } = await import('../src/lib/db/client');
  const { placeInterestFacts } = await import('../src/lib/db/schema');
  const { eq } = await import('drizzle-orm');
  const rows = await db.select().from(placeInterestFacts).where(eq(placeInterestFacts.interestKey, 'birding'));
  const names = new Set<string>();
  for (const r of rows) {
    const hb = (r.facts as Record<string, unknown>).headlineBirds;
    for (const raw of Array.isArray(hb) ? hb : []) {
      const name = String(raw).replace(/\s*\(.*$/, '').trim();
      const words = name.split(/\s+/);
      if (words.length < 1 || words.length > 4) continue;
      if (!words.every((w) => /^[A-Z][\p{L}'’.-]*$/u.test(w))) continue;
      if (/^(North|South|East|West|Central|Many|Various|Other)\b/.test(name) && words.length > 2) continue;
      names.add(name);
    }
  }
  const sorted = [...names].sort((a, b) => a.localeCompare(b));
  writeFileSync(join(__dirname, '..', 'src', 'lib', 'text', 'bird-names.ts'), `// Generated by scripts/build-bird-case-list.ts from the birding headline birds. Do not edit by hand.\nexport const BIRD_NAMES: readonly string[] = ${JSON.stringify(sorted)};\n`);
  console.log(sorted.length, 'bird names', sorted.slice(0, 12).join(' | '));
  process.exit(0);
})().catch((e) => { console.log('ERR', e.cause?.message ?? e.message); process.exit(1); });
